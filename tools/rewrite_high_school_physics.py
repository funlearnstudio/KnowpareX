def make_details(row: tuple[str, str, list[tuple[str, str, str, str]], list[str]]) -> dict[str, Any]:
    intro, application, points, formulas = row
    return {
        "lessonText": [intro, application],
        "readableLesson": [intro, application],
        "formulas": formulas,
        "keyPoints": [
            {"topic": topic, "explanation": explanation, "example": example, "commonTrap": trap}
            for topic, explanation, example, trap in points
        ],
    }


def rewrite(path: Path, *, batch_size: int) -> dict[str, Any]:
    data = load_curriculum_js(path)
    books = [book for book in data.get("physics", []) if book.get("stage") == "high_school"]
    titles = [unit.get("name") for book in books for unit in book.get("units", [])]
    missing = sorted(set(titles) - set(LESSONS))
    extra = sorted(set(LESSONS) - set(titles))
    if missing or extra:
        raise SystemExit(f"策展資料與課程標題不一致：missing={missing}, extra={extra}")

    STATE.parent.mkdir(parents=True, exist_ok=True)
    completed = 0
    failed: list[dict[str, Any]] = []
    for book in books:
        units = book.get("units", [])
        for offset in range(0, len(units), max(1, batch_size)):
            batch = units[offset:offset + max(1, batch_size)]
            for unit in batch:
                unit["lessonDetails"] = make_details(LESSONS[unit["name"]])
                issues = semantic_issues("physics", unit["name"], unit["lessonDetails"])
                if issues:
                    failed.append({"title": unit["name"], "issues": issues})
                else:
                    completed += 1
            # Atomic-enough checkpoint at every small batch: write JS, then state.
            write_curriculum_js(path, data)
            STATE.write_text(json.dumps({
                "subject": "physics", "stage": "high_school", "completed": completed,
                "failed": failed, "last_book": book.get("book"),
                "last_offset": offset + len(batch),
            }, ensure_ascii=False, indent=2), encoding="utf-8")
    return {"completed": completed, "failed": failed, "total": len(titles)}


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--file", type=Path, default=CURRICULUM)
    parser.add_argument("--batch-size", type=int, default=4)
    parser.add_argument("--no-backup", action="store_true")
    args = parser.parse_args()
    if not args.no_backup:
        stamp = datetime.now().strftime("%Y%m%d_%H%M%S")
        backup = args.file.with_name(args.file.name + f".before_high_school_physics_{stamp}")
        shutil.copy2(args.file, backup)
        print(f"backup={backup}")
    report = rewrite(args.file, batch_size=args.batch_size)
    print(json.dumps(report, ensure_ascii=False, indent=2))
    return 0 if not report["failed"] else 2


if __name__ == "__main__":
    raise SystemExit(main())
